import type { ReactNode } from "react";

// Inline icons, so the app needs no icon library. Every icon is drawn on the
// same 24-unit grid with the same stroke, and comes in one of three sizes so
// buttons line up: 16 for toolbar, list and message actions (the default),
// 18 for the composer's main buttons, 12 inside small chips.

type IconSize = 12 | 16 | 18;
interface IconProps {
  size?: IconSize;
}

function Svg({
  size = 16,
  filled = false,
  children
}: IconProps & { filled?: boolean; children: ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={filled ? "currentColor" : "none"}
      stroke={filled ? "none" : "currentColor"}
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  );
}

